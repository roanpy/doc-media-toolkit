"""Minimal runtime i18n for the video/image library workspaces.

Chinese literals stay in the GUI modules as translation keys; English text is
looked up here.  Unknown keys fall back to the Chinese source so partial
coverage never breaks the UI.
"""

from __future__ import annotations

from pptx_tools.language import detect_language as _detect_system_language

_LANGUAGE: str | None = None


def current_language() -> str:
    global _LANGUAGE
    if _LANGUAGE is None:
        _LANGUAGE = _detect_system_language("PPTX_TOOLS_LANG")
    return _LANGUAGE


def set_language(language: str) -> None:
    """Override the language (used by tests and the settings toggle)."""
    global _LANGUAGE
    _LANGUAGE = "en" if str(language).lower().startswith("en") else "zh"


# English translations keyed by the exact Chinese literal in the GUI modules.
TRANSLATIONS: dict[str, str] = {}


def tr(text: str) -> str:
    if current_language() == "zh" or not text:
        return text
    return TRANSLATIONS.get(text, text)


